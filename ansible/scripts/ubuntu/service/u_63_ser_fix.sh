#!/bin/bash
# ============================================================
# U-63 (중) sudo 명령어 접근 관리 - 조치 스크립트
# 분류: 서비스관리 | 대상: Ubuntu (ubuntu)
# 주의: 설정 파일을 변경하는 경우 원본을 .bak_<시각> 으로 백업합니다.
#       운영 서버 적용 전 반드시 테스트 서버에서 먼저 검증하세요.
# 실행: sudo bash u_63_ser_fix.sh
# ============================================================

# JSON 이스케이프 유틸 (따옴표/개행 처리)
json_esc() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="$(printf '%s' "$s" | tr '\n' ' ')"
    printf '%s' "$s"
}

# ============================================================
# 1. 기본 정보
# ============================================================
FIX_ID="U-63"
CATEGORY="서비스관리"
RISK_LEVEL="중"

# ============================================================
# 2~4. 현재 상태 확인 후 필요 시 조치 실행
#   STATUS 값: 조치완료 | 조치불필요 | 조치실패 | 수동조치필요
# ============================================================
FILE="/etc/sudoers"
if [ ! -f "$FILE" ]; then
    STATUS="조치불필요"; ACTION="$FILE 파일이 존재하지 않음"
else
    OWNER=$(stat -c '%U' "$FILE" 2>/dev/null)
    PERM=$(stat -c '%a' "$FILE" 2>/dev/null)
    PERM_NUM=$((10#$PERM))
    if [ "$OWNER" = "root" ] && [ "$PERM_NUM" -le 640 ]; then
        STATUS="조치불필요"; ACTION="이미 기준을 충족함(소유자:$OWNER 권한:$PERM)"
    else
        chown root "$FILE"
        chmod 640 "$FILE"
        FIX_RC=$?
        if [ $FIX_RC -eq 0 ]; then
            STATUS="조치완료"; ACTION="chown root, chmod 640 을 적용함"
        else
            STATUS="조치실패"; ACTION="권한 변경 실패"
        fi
    fi
fi

# ============================================================
# 5. JSON 출력
# ============================================================
cat <<EOF
{
  "fix_id": "$(json_esc "$FIX_ID")",
  "category": "$(json_esc "$CATEGORY")",
  "status": "$(json_esc "$STATUS")",
  "action": "$(json_esc "$ACTION")",
  "hostname": "$(hostname)",
  "risk_level": "$(json_esc "$RISK_LEVEL")"
}
EOF

# ============================================================
# 6. 정상 종료
# ============================================================
exit 0
