#!/bin/bash
# ============================================================
# U-49 (상) DNS 보안 버전 패치 - 조치 스크립트
# 분류: 서비스관리 | 대상: Ubuntu (ubuntu)
# 주의: 설정 파일을 변경하는 경우 원본을 .bak_<시각> 으로 백업합니다.
#       운영 서버 적용 전 반드시 테스트 서버에서 먼저 검증하세요.
# 실행: sudo bash u_49_ser_fix.sh
# ============================================================

# JSON 이스케이프 유틸 (따옴표/개행 처리)
json_esc() {
    local s="$1"
    s="${s//\\/\\\\}"
    s="${s//\"/\\\"}"
    s="$(printf '%s' "$s" | tr '\n' ' ')"
    printf '%s' "$s"
}

# ============================================================
# 1. 기본 정보
# ============================================================
FIX_ID="U-49"
CATEGORY="서비스관리"
RISK_LEVEL="상"

# ============================================================
# 2~4. 현재 상태 확인 후 필요 시 조치 실행
#   STATUS 값: 조치완료 | 조치불필요 | 조치실패 | 수동조치필요
# ============================================================
BIND_ACTIVE="no"
for svc in "named" "bind9"; do
    systemctl is-active --quiet "$svc" 2>/dev/null && BIND_ACTIVE="yes"
done

if [ "$BIND_ACTIVE" = "no" ]; then
    STATUS="조치불필요"
    ACTION="DNS(BIND) 서비스 미사용 또는 비활성 상태로 조치 대상 아님"
else
    apt-get update -qq && apt-get install -y --only-upgrade bind9 >/tmp/u49_fix.log 2>&1
    FIX_RC=$?
    if [ $FIX_RC -eq 0 ]; then
        STATUS="조치완료"
        ACTION="bind9 패키지를 최신 버전으로 업데이트함(패키지 매니저 기준). 정기 패치 정책 수립은 별도 필요"
    else
        STATUS="조치실패"
        ACTION="패키지 업데이트 실패. /tmp/u49_fix.log 확인 필요"
    fi
fi

# ============================================================
# 5. JSON 출력
# ============================================================
cat <<EOF
{
  "fix_id": "$(json_esc "$FIX_ID")",
  "category": "$(json_esc "$CATEGORY")",
  "status": "$(json_esc "$STATUS")",
  "action": "$(json_esc "$ACTION")",
  "hostname": "$(hostname)",
  "risk_level": "$(json_esc "$RISK_LEVEL")"
}
EOF

# ============================================================
# 6. 정상 종료
# ============================================================
exit 0
